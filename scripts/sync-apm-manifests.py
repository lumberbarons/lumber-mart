#!/usr/bin/env python3
"""Generate the explicit APM layout from canonical portable manifests.

An apm.yml beside .apm/ selects APM's skill-bundle route ahead of the portable
plugin route. Skills remain in skills/; no second skill tree is maintained.
Run with --check in CI to reject stale metadata or a missing layout marker.
"""

import argparse
import json
from pathlib import Path


MARKER = """# APM compatibility

This directory makes the generated `../apm.yml` an explicit APM layout.
APM installs the existing `../skills/` tree as a skill bundle, even when the
portable `../plugin.json` and Claude manifest are present.

Generated by `scripts/sync-apm-manifests.py`; do not add skill copies here.
"""


def render(manifest: dict) -> str:
    fields = {key: manifest[key] for key in ("name", "version", "description")}
    fields["author"] = manifest["author"]["name"]
    fields["license"] = manifest["license"]
    # JSON string literals are YAML scalars, including multiline descriptions.
    return "# Generated from plugin.json by scripts/sync-apm-manifests.py.\n" + "".join(
        f"{key}: {json.dumps(value, ensure_ascii=False)}\n" for key, value in fields.items()
    )


def sync(root: Path, check: bool) -> list[str]:
    problems = []
    for manifest_path in sorted((root / "plugins").glob("*/plugin.json")):
        manifest = json.loads(manifest_path.read_text())
        plugin = manifest_path.parent
        for path, expected in ((plugin / "apm.yml", render(manifest)),
                               (plugin / ".apm/README.md", MARKER)):
            if check:
                if not path.is_file() or path.read_text() != expected:
                    problems.append(f"out of sync: {path.relative_to(root)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    problems = sync(Path(__file__).resolve().parent.parent, args.check)
    for problem in problems:
        print(problem)
    if problems:
        print("Run python3 scripts/sync-apm-manifests.py to regenerate.")
    return int(bool(problems))


if __name__ == "__main__":
    raise SystemExit(main())
